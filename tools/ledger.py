#!/usr/bin/env python3
"""
ledger — one table of what every eval case has shown so far, built from the retained runs.

WHY THIS EXISTS
---------------
evals/RESULTS.md describes only the latest run, which may cover one case of sixty-six. Whether a
skill earns its place is a question about all runs, so this reads every evals/results/*/ folder and
reports, per case, the most recent run that had both a without and a with side.

  --write   regenerate evals/LEDGER.md
  --check   exit 1 if evals/LEDGER.md differs from what the retained results produce

Rules it applies (they are the ones evals/README.md and RESULTS.md already state):
  * a try that errored (runner failure, not a product failure) is not counted;
  * a run whose folder name says contaminated or leaky is shown but never trusted;
  * fewer than 3 tries per side is "thin": a gap there is a hint, not a finding;
  * runs are ordered by the `started` stamp in meta.json, never by file time (git rewrites that).

Stdlib only.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "evals" / "cases"
RESULTS = ROOT / "evals" / "results"
OUT = ROOT / "evals" / "LEDGER.md"
PLUGIN_JSON = ROOT / "plugin" / ".claude-plugin" / "plugin.json"
UNTRUSTED = ("contaminated", "leaky")
SOLID = 3  # tries per side before a verdict is more than a hint


def load_runs():
    """{case: {run folder: {"started", "version", "arms": {arm: [result, ...]}}}}"""
    runs = {}
    for meta_path in sorted(RESULTS.glob("*/meta.json")):
        folder = meta_path.parent
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for path in folder.glob("*/*/result.json"):
            try:
                row = json.loads(path.read_text(encoding="utf-8"))
            except ValueError:
                continue
            if row.get("errored") or not row.get("case") or row.get("arm") not in ("with", "without"):
                continue
            entry = runs.setdefault(row["case"], {}).setdefault(folder.name, {
                "started": str(meta.get("started", "")), "version": str(meta.get("version", "?")),
                "arms": {"with": [], "without": []}})
            entry["arms"][row["arm"]].append(row)
    return runs


def verdict(passed_without, n_without, passed_with, n_with):
    gap = passed_with / n_with - passed_without / n_without
    if gap >= 0.5:
        return "helps"
    if gap <= -0.5:
        return "HURTS"
    if gap > 0:
        return "leans helps"
    if gap < 0:
        return "leans hurts"
    return "no difference"


def build(runs=None, current_version=None):
    runs = load_runs() if runs is None else runs
    if current_version is None:
        current_version = json.loads(PLUGIN_JSON.read_text(encoding="utf-8")).get("version", "?")
    rows, never = [], []
    for case_dir in sorted(p for p in CASES.iterdir() if p.is_dir()):
        case = case_dir.name
        try:
            skill = json.loads((case_dir / "expect.json").read_text(encoding="utf-8")).get("skill", "?")
        except (OSError, ValueError):
            skill = "?"
        paired = [(entry["started"], name, entry) for name, entry in runs.get(case, {}).items()
                  if entry["arms"]["with"] and entry["arms"]["without"]]
        if not paired:
            never.append((case, skill, bool(runs.get(case))))
            continue
        started, name, entry = max(paired)
        w, o = entry["arms"]["with"], entry["arms"]["without"]
        pw, po = sum(1 for r in w if r.get("passed")), sum(1 for r in o if r.get("passed"))
        cost = lambda rs: sum(r.get("cost_usd") or 0 for r in rs) / len(rs)
        flags = []
        if min(len(w), len(o)) < SOLID:
            flags.append("thin")
        if any(t in name for t in UNTRUSTED):
            flags.append("untrusted run")
        if entry["version"] != current_version:
            flags.append(f"ran on {entry['version']}")
        models = sorted({r.get("model") or "?" for r in w + o})
        rows.append({"case": case, "skill": skill, "started": started, "run": name,
                     "without": f"{po}/{len(o)}", "with": f"{pw}/{len(w)}",
                     "verdict": verdict(po, len(o), pw, len(w)),
                     "cost": f"${cost(o):.2f} -> ${cost(w):.2f}",
                     "models": ", ".join(models), "flags": ", ".join(flags)})
    return rows, never, current_version


def render(rows, never, current_version):
    count = {}
    for r in rows:
        count[r["verdict"]] = count.get(r["verdict"], 0) + 1
    solid = {}
    for r in rows:
        if "thin" not in r["flags"] and "untrusted" not in r["flags"]:
            solid[r["verdict"]] = solid.get(r["verdict"], 0) + 1
    lines = [
        "# Ledger - what every case has shown so far",
        "",
        "Generated by `python tools/ledger.py --write` from `evals/results/*/`. Do not edit by hand.",
        f"Current plugin version: {current_version}. For each case: the most recent run that had both a",
        "without and a with side. A gap of two or more passes in three tries is a signal; fewer than three",
        "tries per side is `thin` (a hint only); a run in a folder named contaminated/leaky is `untrusted`.",
        "",
        "**All pairs:** " + ", ".join(f"{v} {n}" for v, n in sorted(count.items())) +
        f". **Solid only (3+ tries, trusted run):** " +
        (", ".join(f"{v} {n}" for v, n in sorted(solid.items())) or "none") + ".",
        f"**Never compared with both sides:** {len(never)} of {len(rows) + len(never)} cases.",
        "",
        "| Case | Skill | Run started | Without | With | Verdict | Cost / try | Notes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    order = {"HURTS": 0, "leans hurts": 1, "no difference": 2, "leans helps": 3, "helps": 4}
    for r in sorted(rows, key=lambda r: (order[r["verdict"]], r["case"])):
        lines.append(f"| `{r['case']}` | {r['skill']} | {r['started']} | {r['without']} | {r['with']} | "
                     f"**{r['verdict']}** | {r['cost']} | {r['flags']} |")
    lines += ["", "## Never compared with both sides", ""]
    if never:
        lines += ["| Case | Skill | Some run exists |", "|---|---|---|"]
        lines += [f"| `{c}` | {s} | {'one side only' if some else 'no'} |" for c, s, some in never]
    else:
        lines.append("None.")
    lines += ["",
              "Per-run detail: `evals/RESULTS.md` (latest run only) and `evals/results/<run>/`.",
              "Loading counts changed in 4.66: runs before then may under-report that the skill was opened",
              "(a `cat` of SKILL.md was not counted). The pass/fail columns are unaffected.", ""]
    return "\n".join(lines)


def main(argv):
    text = render(*build())
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have.replace("\r\n", "\n") != text:
            print("evals/LEDGER.md is stale: run python tools/ledger.py --write")
            return 1
        return 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
